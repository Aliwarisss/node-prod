/* Work out who owns each clashing artifact name: the act that loads first (the producer).
   Writes acts/reconcile.js — loaded after every act — which gives each clashing name to its owner,
   drops later copies that are left with no name, and points packs at the owner.
   usage: node acts/_ownership.cjs   (from the-book/sdlc) */
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const B = path.join(__dirname, '..') + '/';
const ACTS = ['plan', 'design', 'build', 'verify', 'release', 'operate', 'evolve'];
const ctx = { console }; ctx.window = ctx; vm.createContext(ctx);
const run = (f) => vm.runInContext(fs.readFileSync(B + f + '.js', 'utf8'), ctx, { filename: f });
['model', 'system', 'roadmap', 'knowledge', 'lenses', 'artifacts', 'roles'].forEach(run);
const origin = {};
Object.keys(ctx.NODE_ARTIFACTS).forEach((id) => (origin[id] = 0));
['acts/discover-units', 'acts/discover', 'acts/discover-depth', 'acts/discover-agile', 'acts/discover-prompts'].forEach(run);
ACTS.forEach((a, i) => {
  for (const f of [`acts/${a}-library`, `acts/${a}-units`, `acts/${a}`, `acts/${a}-depth`]) run(f);
  Object.keys(ctx.NODE_ARTIFACTS).forEach((id) => { if (origin[id] === undefined) origin[id] = i + 1; });
});
const A = ctx.NODE_ARTIFACTS;
const stub = (id) => /^(vin|ops)-/.test(id) || A[id].external;
const by = {};
for (const [id, a] of Object.entries(A)) for (const n of a.aliases || []) (by[n] = by[n] || new Set()).add(id);
const owner = {};
for (const [n, ids] of Object.entries(by)) {
  if (ids.size < 2) continue;
  /* the earliest act wins; between two of the same act, a real template beats a stub copy */
  owner[n] = [...ids].sort((x, y) => (origin[x] - origin[y]) || (stub(x) - stub(y)))[0];
}
const out = `/*
 * Reconcile the artifact library across the eight acts. Generated by acts/_ownership.cjs — do not edit by hand.
 * Several acts carry templates for what they receive from an earlier act. A name belongs to the template
 * of the act that produces it (the earliest to load); later copies give the name up, a copy left with no
 * name is removed, and packs that listed it point at the owner instead.
 */
(function () {
  const A = window.NODE_ARTIFACTS;
  const OWNER = ${JSON.stringify(owner, null, 2).replace(/\n/g, '\n  ')};
  Object.entries(OWNER).forEach(([name, id]) => Object.entries(A).forEach(([k, a]) => { if (k !== id && a.aliases) a.aliases = a.aliases.filter((n) => n !== name); }));
  const gone = {};
  Object.entries(A).forEach(([k, a]) => { if (!a.aliases || !a.aliases.length) gone[k] = true; });
  /* packs: a part that names a removed template points at the template that now owns its first name */
  const firstName = ${JSON.stringify(Object.fromEntries(Object.entries(A).map(([k, a]) => [k, (a.aliases || [])[0]])))};
  Object.values(A).forEach((a) => {
    if (a.tpl && a.tpl.fmt === 'pack') a.tpl.parts = a.tpl.parts.map(([p, note]) => (gone[p] && OWNER[firstName[p]] ? [OWNER[firstName[p]], note] : [p, note]));
  });
  Object.keys(gone).forEach((k) => delete A[k]);
})();
`;
fs.writeFileSync(B + 'acts/reconcile.js', out);
console.log('clashing names:', Object.keys(owner).length);
